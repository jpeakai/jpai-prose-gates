#!/usr/bin/env bun
// Render the Example Pages under docs/examples from the golden fixtures and the
// Sweep Snapshot. Every finding on a page is the gate's output at render time,
// and every after is what --fix writes, so a page cannot drift from the code:
// a fixture whose fix no longer matches stops the render, and the test in
// tests/examples-pages.test.ts fails when a committed page differs from a fresh one.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { CATEGORIES, checkMarkdown, fixMarkdown, RULES } from "../src/index.ts";

const REPO_URL = "https://github.com/jpeakai/jpai-prose-gates";
const FIX_FIXTURES = join("tests", "fixtures", "fix");
const PARAGRAPH_FIXTURES = join("tests", "fixtures", "paragraph");
const EVAL_FIXTURES = join("evals", "prose-gates", "evals", "fixtures");
const SNAPSHOT = join("evals", "results", "sweep.json");
export const PAGES = {
  fixes: join("docs", "examples", "fixes.md"),
  evals: join("docs", "examples", "agent-evals.md"),
} as const;

const BANNER = (sources: string): string =>
  `<!-- Generated by scripts/examples-pages.ts from ${sources}. Do not edit: change the source and run make fix. -->`;

export interface Cell {
  case: string;
  question: string;
  fixture: string;
  target: string;
  harness: string;
  model: string;
  tier: number;
  verdict: string;
  turns: number;
  tool_calls: number;
  seconds: number;
  cost_usd: number;
  rewrite: string;
  closing_message: string;
}

export interface Snapshot {
  swept_on: string;
  cells: Cell[];
}

const CELL_KEYS: Record<keyof Cell, "string" | "number"> = {
  case: "string",
  question: "string",
  fixture: "string",
  target: "string",
  harness: "string",
  model: "string",
  tier: "number",
  verdict: "string",
  turns: "number",
  tool_calls: "number",
  seconds: "number",
  cost_usd: "number",
  rewrite: "string",
  closing_message: "string",
};

const isRecord = (v: unknown): v is Record<string, unknown> => typeof v === "object" && v !== null;

export const parseSnapshot = (raw: unknown): Snapshot => {
  if (!isRecord(raw) || typeof raw.swept_on !== "string" || !Array.isArray(raw.cells) || raw.cells.length === 0) {
    throw new Error(`${SNAPSHOT} must hold swept_on and a non-empty cells list`);
  }
  for (const [i, cell] of raw.cells.entries()) {
    for (const [key, type] of Object.entries(CELL_KEYS)) {
      if (!isRecord(cell) || typeof cell[key] !== type) throw new Error(`${SNAPSHOT}: cell ${i} has no ${type} ${key}`);
    }
  }
  return raw as unknown as Snapshot;
};

// A fence one backtick longer than any run inside the text, so no content closes it.
const fence = (text: string, lang = "text"): string => {
  const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const ticks = "`".repeat(longest + 1);
  return `${ticks}${lang}\n${text.replace(/\n+$/, "")}\n${ticks}`;
};

const findingsOf = async (src: string, file: string): Promise<string[]> =>
  (await checkMarkdown(src, file)).map((f) => `${file}:${f.line} ${f.rule} ${f.message}`);

const sentenceCase = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);

const ruleOfFixture = (name: string): string => {
  const ids = RULES.map((r) => r.id)
    .filter((id) => name === id || name.startsWith(`${id}-`))
    .sort((a, b) => b.length - a.length);
  if (!ids[0]) throw new Error(`fix fixture ${name} names no rule`);
  return ids[0];
};

const fixtureTitle = (name: string, rule: string): string => {
  const rest = name.slice(rule.length + 1);
  if (rest.startsWith("then-")) return `Followed by ${rest.slice("then-".length)}`;
  return sentenceCase(rest.replaceAll("-", " "));
};

const read = (...parts: string[]): Promise<string> => readFile(join(...parts), "utf8");

const fixtureDirs = async (root: string): Promise<string[]> =>
  (await readdir(root, { withFileTypes: true }))
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

const fixSection = async (name: string, rule: string): Promise<string[]> => {
  const input = await read(FIX_FIXTURES, name, "input.md");
  const expected = await read(FIX_FIXTURES, name, "expected.md");
  if ((await fixMarkdown(input)) !== expected) throw new Error(`fix fixture ${name}: --fix no longer writes expected.md`);
  return [
    `#### ${fixtureTitle(name, rule)}`,
    "",
    `The gate reports, from [\`${name}\`](${REPO_URL}/tree/main/${FIX_FIXTURES}/${name}):`,
    "",
    fence((await findingsOf(input, "input.md")).join("\n")),
    "",
    "Before:",
    "",
    fence(input),
    "",
    "After `--fix`:",
    "",
    fence(expected),
    "",
  ];
};

const paragraphSection = async (name: string): Promise<string[]> => {
  const before = await read(PARAGRAPH_FIXTURES, name, "before.md");
  const fixed = await readFile(join(PARAGRAPH_FIXTURES, name, "fixed.md"), "utf8").catch(() => undefined);
  const after = fixed ?? (await read(PARAGRAPH_FIXTURES, name, "after.md"));
  if (fixed !== undefined && (await fixMarkdown(before)) !== fixed) {
    throw new Error(`paragraph fixture ${name}: --fix no longer writes fixed.md`);
  }
  if ((await checkMarkdown(after, "after.md")).length > 0) throw new Error(`paragraph fixture ${name}: its after fails`);
  return [
    `### ${sentenceCase(name.replaceAll("-", " "))}`,
    "",
    `The gate reports, from [\`${name}\`](${REPO_URL}/tree/main/${PARAGRAPH_FIXTURES}/${name}):`,
    "",
    fence((await findingsOf(before, "before.md")).join("\n")),
    "",
    "Before:",
    "",
    fence(before),
    "",
    fixed === undefined ? "Rewritten by hand from the finding, with no word changed:" : "After `--fix`:",
    "",
    fence(after),
    "",
  ];
};

export const renderFixes = async (): Promise<string> => {
  const fixtures = await fixtureDirs(FIX_FIXTURES);
  const lines = [
    BANNER("tests/fixtures"),
    "",
    "# Fixes, before and after",
    "",
    "Each example is a golden fixture under `tests/fixtures`, and the tests hold every one to the code.",
    "The findings are what the gate reports today, and each after is exactly what `--fix` writes.",
    "[RULES.md](../../RULES.md) has one short example per rule, and this page has the longer cases.",
    "",
  ];
  for (const category of CATEGORIES) {
    const rules = RULES.filter((r) => r.category === category && fixtures.some((f) => ruleOfFixture(f) === r.id));
    if (rules.length === 0) continue;
    lines.push(`## ${sentenceCase(category)}`, "");
    for (const rule of rules) {
      lines.push(`### ${rule.id}`, "");
      for (const name of fixtures.filter((f) => ruleOfFixture(f) === rule.id)) lines.push(...(await fixSection(name, rule.id)));
    }
  }
  lines.push(
    "## Reported, then rewritten",
    "",
    "A paragraph over its budget has no fixer, because where it breaks depends on its topics.",
    "Its finding names the sentences to break after, and a rewrite that follows it changes no word.",
    "A list rule can settle a long paragraph first, as the last case shows.",
    "",
  );
  for (const name of await fixtureDirs(PARAGRAPH_FIXTURES)) lines.push(...(await paragraphSection(name)));
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
};

const modelKey = (c: Cell): string => `${c.harness}/${c.model}`;

const money = (usd: number): string => `$${usd.toFixed(4)}`;

const models = (cells: Cell[]): Cell[] =>
  [...new Map(cells.map((c) => [modelKey(c), c])).values()].sort(
    (a, b) => a.tier - b.tier || a.harness.localeCompare(b.harness) || a.model.localeCompare(b.model),
  );

const mark = (c: Cell): string => (c.verdict === "pass" ? "pass" : c.verdict);

const cellSection = async (c: Cell): Promise<string[]> => {
  const today = await findingsOf(c.rewrite, c.target);
  return [
    `### ${modelKey(c)}, tier ${c.tier}`,
    "",
    `Graded ${mark(c)} in ${c.turns} turns and ${c.tool_calls} tool calls, for about ${money(c.cost_usd)} over ${c.seconds} seconds.`,
    "",
    fence(c.rewrite, "text"),
    "",
    ...(today.length === 0
      ? ["The gate reports nothing on this rewrite today.", ""]
      : ["The gate as it is today still reports this rewrite:", "", fence(today.join("\n")), ""]),
    "What the agent said it did:",
    "",
    fence(c.closing_message),
    "",
  ];
};

const caseSection = async (cells: Cell[]): Promise<string[]> => {
  const first = cells[0] as Cell;
  const seed = await read(EVAL_FIXTURES, first.fixture, first.target);
  const fixed = await fixMarkdown(seed);
  return [
    `## ${sentenceCase(first.question)}`,
    "",
    `The Seed Document, \`${first.target}\`:`,
    "",
    fence(seed),
    "",
    "The gate reports:",
    "",
    fence((await findingsOf(seed, first.target)).join("\n")),
    "",
    ...(fixed === seed
      ? ["`--fix` leaves it alone, so the finding's message is all the agent has to go on.", ""]
      : ["`--fix` writes this, and the agent works from what it leaves:", "", fence(fixed), ""]),
    ...(await Promise.all(cells.map(cellSection))).flat(),
  ];
};

export const renderAgentEvals = async (snapshot: Snapshot): Promise<string> => {
  const columns = models(snapshot.cells);
  const cases = [...new Set(snapshot.cells.map((c) => c.case))];
  const byCase = (k: string): Cell[] =>
    columns.flatMap((m) => snapshot.cells.filter((c) => c.case === k && modelKey(c) === modelKey(m)));
  const lines = [
    BANNER("evals/results/sweep.json"),
    "",
    "# Agent evals",
    "",
    "Each case hands an agent one Seed Document that fails one rule, with no task but to make the gate pass.",
    "The finding's message is the agent's only guide, since `--fix` cannot settle these cases.",
    `The rewrites below are the files each agent left in the sweep of ${snapshot.swept_on}.`,
    "Every finding shown is from the gate as it is today, so a rule that has tightened since shows here.",
    "",
    "To refresh it, run a new sweep with `make evals` and keep it with `make evals-snapshot`.",
    "Then `make fix` renders this page again.",
    "",
    "## By case",
    "",
    `| Case | ${columns.map(modelKey).join(" | ")} |`,
    `|---|${columns.map(() => "---|").join("")}`,
  ];
  for (const k of cases) {
    const row = byCase(k);
    lines.push(
      `| ${sentenceCase((row[0] as Cell).question)} | ${columns
        .map((m) => row.find((c) => modelKey(c) === modelKey(m)))
        .map((c) => (c ? `${mark(c)}, ${c.turns} turns` : "not run"))
        .join(" | ")} |`,
    );
  }
  lines.push(
    "",
    "## By model",
    "",
    "Tier is the eval plugin catalogue's family tier, from the smallest model of a line to the largest.",
    "",
    "| Model | Tier | Passed | Mean turns | Total cost |",
    "|---|---|---|---|---|",
  );
  for (const m of columns) {
    const mine = snapshot.cells.filter((c) => modelKey(c) === modelKey(m));
    const turns = mine.reduce((n, c) => n + c.turns, 0) / mine.length;
    const cost = mine.reduce((n, c) => n + c.cost_usd, 0);
    const passed = mine.filter((c) => c.verdict === "pass").length;
    lines.push(`| ${modelKey(m)} | ${m.tier} | ${passed} of ${mine.length} | ${turns.toFixed(1)} | ${money(cost)} |`);
  }
  lines.push("");
  for (const k of cases) lines.push(...(await caseSection(byCase(k))));
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
};

export const loadSnapshot = async (): Promise<Snapshot> => parseSnapshot(JSON.parse(await read(SNAPSHOT)));

export const renderAll = async (): Promise<Record<keyof typeof PAGES, string>> => ({
  fixes: await renderFixes(),
  evals: await renderAgentEvals(await loadSnapshot()),
});

const printHelp = (): void => {
  console.log(
    [
      "Usage: bun run scripts/examples-pages.ts [--check]",
      "",
      `Render ${Object.values(PAGES).join(" and ")} from the fixtures and ${SNAPSHOT}.`,
      "",
      "Options:",
      "  --check     Write nothing, and exit 1 when a committed page differs from a fresh render",
      "  -h, --help  Show this help and exit",
    ].join("\n"),
  );
};

const main = async (): Promise<void> => {
  const { values } = parseArgs({
    args: Bun.argv.slice(2),
    options: { check: { type: "boolean", default: false }, help: { type: "boolean", short: "h", default: false } },
    strict: true,
  });
  if (values.help) {
    printHelp();
    return;
  }
  const pages = await renderAll();
  for (const [key, path] of Object.entries(PAGES) as [keyof typeof PAGES, string][]) {
    if (!values.check) {
      await writeFile(path, pages[key]);
      console.log(`wrote ${path}`);
    } else if ((await readFile(path, "utf8").catch(() => "")) !== pages[key]) {
      console.error(`error: ${path} is stale; run make fix`);
      process.exit(1);
    }
  }
};

if (import.meta.main) {
  main().catch((err: unknown) => {
    console.error(`error: ${err instanceof Error ? err.message : String(err)}`);
    process.exit(1);
  });
}
